    private void InscripciónActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_InscripciónActionPerformed
        escritorio.removeAll();
    escritorio.repaint();
    
    VistaInscripcion vi = new VistaInscripcion();
    vi.cargarAlumnos();
    vi.cargarMaterias();
    vi.setVisible(true);
    escritorio.add(vi);
    
    int x = (escritorio.getWidth() - vi.getWidth()) / 2;
    int y = (escritorio.getHeight() - vi.getHeight()) / 2;
    vi.setLocation(x, y);
    
    escritorio.moveToFront(vi);
    }//GEN-LAST:event_InscripciónActionPerformed

