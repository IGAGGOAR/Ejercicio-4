    private void AgregarMateriaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AgregarMateriaActionPerformed
    escritorio.removeAll();
    escritorio.repaint();
    
    VistaMaterias vm = new VistaMaterias(listaMaterias);
    vm.setVisible(true);
    escritorio.add(vm);
    
    // Centrar subventana
    int x = (escritorio.getWidth() - vm.getWidth()) / 2;
    int y = (escritorio.getHeight() - vm.getHeight()) / 2;
    vm.setLocation(x, y);
    
    escritorio.moveToFront(vm);
    }//GEN-LAST:event_AgregarMateriaActionPerformed

